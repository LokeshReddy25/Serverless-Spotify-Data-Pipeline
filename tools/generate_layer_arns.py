"""Regenerate infra/lambda_layers.py from the official AWS SDK for pandas layer list.

Usage (needs network access; no AWS credentials):
    python tools/generate_layer_arns.py [RELEASE] [PYTHON_VERSION]
    python tools/generate_layer_arns.py 3.18.0 3.14

It downloads docs/source/layers.rst for that release from the aws/aws-sdk-pandas GitHub repository
(the source of https://aws-sdk-pandas.readthedocs.io/en/<release>/layers.html), keeps the x86_64
rows for the given Python version, and writes them verbatim. No ARN is constructed or guessed.
"""
import datetime
import re
import sys
import urllib.request
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "infra" / "lambda_layers.py"
SOURCE = "https://raw.githubusercontent.com/aws/aws-sdk-pandas/{release}/docs/source/layers.rst"
ROW = re.compile(r"\|\s*([a-z0-9-]+)\s*\|\s*{py}\s*\|\s*x86_64\s*\|\s*(arn:[^\s|]+)\s*\|")


def parse(rst, python_version):
    pattern = re.compile(ROW.pattern.replace("{py}", re.escape(python_version)))
    layer = f"AWSSDKPandas-Python{python_version.replace('.', '')}"
    arns = {}
    for region, arn in pattern.findall(rst):
        if not re.fullmatch(rf"arn:aws(-cn|-us-gov)?:lambda:{re.escape(region)}:\d{{12}}:layer:{layer}:\d+", arn):
            raise ValueError(f"unexpected ARN for {region}: {arn}")
        if region in arns and arns[region] != arn:
            raise ValueError(f"two different ARNs for {region}")
        arns[region] = arn
    if not arns:
        raise ValueError(f"no x86_64 rows for Python {python_version}")
    return arns


def render(release, python_version, url, arns):
    lines = [
        f'"""AWS SDK for pandas managed Lambda layer ARNs: release {release}, Python {python_version}, x86_64.',
        "",
        "GENERATED by tools/generate_layer_arns.py - do not edit by hand. Copied verbatim from",
        f"{url}",
        f"on {datetime.date.today().isoformat()}. Regions not listed here have no documented layer for this release.",
        '"""',
        "",
        f'AWSSDKPANDAS_RELEASE = "{release}"',
        f'PYTHON_VERSION = "{python_version}"',
        'ARCHITECTURE = "x86_64"',
        f'SOURCE_URL = "{url}"',
        f'DOCS_URL = "https://aws-sdk-pandas.readthedocs.io/en/{release}/layers.html"',
        "",
        "LAYER_ARNS = {",
    ]
    lines += [f'    "{region}": "{arns[region]}",' for region in sorted(arns)]
    lines += ["}", ""]
    return "\n".join(lines)


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    release = argv[0] if argv else "3.18.0"
    python_version = argv[1] if len(argv) > 1 else "3.14"
    url = SOURCE.format(release=release)
    with urllib.request.urlopen(url, timeout=30) as resp:
        rst = resp.read().decode("utf-8")
    arns = parse(rst, python_version)
    OUT.write_text(render(release, python_version, url, arns), encoding="utf-8", newline="\n")
    print(f"wrote {OUT} with {len(arns)} regions")


if __name__ == "__main__":
    main()
